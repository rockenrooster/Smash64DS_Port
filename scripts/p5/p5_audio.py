#!/usr/bin/env python3
"""P5 T7: the landed Remix stages' songs.

A Remix stage's header names its song by Remix's BGM id (First Destination:
0x36, "Final Destination (Melee)"). Each song past the vanilla table is
rendered from the staged Remix build's sequence on Remix's own instrument
bank (scripts/p5/render_remix_bgm.py), and gets a track row
nds_audio_bgm.c appends to its table, so the stage's own song plays by its
own id. Owner decision 3 (2026-10-12): the default track only.

    python scripts/p5/p5_audio.py --staging <remix staging> \
        --stages-root builds/<build>/p5/stages --out builds/<build>/p5/audio

Outputs derive from the user's ROM: a build directory only.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "p4"))
import p4_audio  # noqa: E402
import p5_stages  # noqa: E402


def build_song(staging: Path, bgm_id: int, out: Path, songs: dict[int, str]) -> dict:
    rel = songs.get(bgm_id)
    if rel is None:
        raise SystemExit(f"BGM {bgm_id:#x} has no MIDI line in bass.out")
    name = f"bgm_p5_{bgm_id:02x}"
    output = out / f"{name}.bin"
    # On Remix's own bank (scripts/p5/render_remix_bgm.py): the stages' songs
    # use instruments Remix appends past the vanilla bank.
    subprocess.run([sys.executable, str(HERE / "render_remix_bgm.py"), "--staging", str(staging),
                    "--remix-bgm-id", str(bgm_id), "--repo", str(p4_audio.ROOT),
                    "--sequence-file", str(staging / rel), "--output", str(output)],
                   check=True, capture_output=True)
    meta = json.loads(output.with_suffix(".json").read_text(encoding="utf-8"))
    looping = bool(meta["looping"])
    return {
        "id": bgm_id, "name": name, "source": rel,
        "path": f"nitro:/p5/audio/{name}.bin",
        "stream_bytes": meta["source_pcm_bytes"],
        "loop_start_bytes": meta["loop_start_byte"] if looping else 0,
        "asset_bytes": meta["bytes"],
        "packet_count": meta["packet_count"],
        "loop_packet": meta["loop_packet_index"] if looping else p4_audio.BGM_NO_LOOP,
        "loop_record": meta["loop_record_offset"] if looping else 0,
        "looping": looping,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--staging", type=Path, required=True)
    ap.add_argument("--stages-root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    songs = p4_audio.remix_songs((args.staging / "bass.out").read_text(encoding="utf-8", errors="replace"))
    tracks = []
    seen = set()
    for row in p5_stages.load_registry():
        if row["source"] != "remix" or not row["landed"]:
            continue
        stage = json.loads((args.stages_root / row["name"] / "stage.json").read_text(encoding="utf-8"))
        bgm_id = stage["bgm_id"]
        if bgm_id < p4_audio.VANILLA_BGM_COUNT or bgm_id in seen:
            continue
        seen.add(bgm_id)
        tracks.append(build_song(args.staging, bgm_id, args.out, songs))
    lines = ["/* Generated by scripts/p5/p5_audio.py: the landed Remix stages' songs. */"]
    for t in tracks:
        lines += [
            f"    /* {t['source']} */",
            "    ,",
            "    {",
            f"        {t['id']:#x},",
            f"        \"{t['path']}\",",
            f"        {t['stream_bytes']}u, {t['loop_start_bytes']}u, {t['asset_bytes']}u,",
            f"        {t['packet_count']}u, {t['loop_packet']:#x}u, {t['loop_record']}u,",
            f"        {'TRUE' if t['looping'] else 'FALSE'}",
            "    }",
        ]
    p5_stages.write_if_changed(args.out / "nds_p5_bgm.generated.inc", "\n".join(lines) + "\n")
    for t in tracks:
        print(f"p5_audio: {t['source']} -> {t['name']} ({t['asset_bytes']} B, "
              f"{'loop' if t['looping'] else 'once'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
