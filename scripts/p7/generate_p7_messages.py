"""P7 U6: the unlock messages in the source's style.

The source's seven unlock messages (mnmessage.c:128-149) are I4 sprites --
16 white levels, alpha the level -- of one or two lines: cap height 10,
x-height 8, a 17-pixel line pitch, the first baseline at 10, centred at x 161
(two lines at y 114, one at 123). Arial at 14 px emboldened a quarter pixel
is the closest face (a search over 14). This renders every P7 unlock row's
lines (scripts/p7/messages.json, rows in scripts/p7/unlocks.json order) the
same way, four times supersampled, and writes the table
src/nds/nds_p7_messages.generated.inc -- (unlock row, width, height, x, y,
data offset) -- and the texels to assets/p7/messages.bin (NitroFS
p7/messages.bin: an 8 B header, magic P7MS and the byte count, then each
message's I4 rows, 16-texel aligned, two texels a byte, high nibble first,
G_IM_SIZ_4b, in the staged sprites' TMEM order). Only the table is
resident; the message screen reads its row's texels from the file into its
own heap.

Run by hand after a text change (it needs Pillow, NumPy and the Arial face);
both outputs are committed, so builds need neither.
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "nds" / "nds_p7_messages.generated.inc"
BLOB = ROOT / "assets" / "p7" / "messages.bin"
MAGIC = 0x534D3750  # "P7MS"
FONT = Path("C:/Windows/Fonts/arial.ttf")
SCALE = 4
SIZE = 14.0
STROKE = 1          # a quarter pixel at 4x
LINE_H = 17
BASELINE = 10
CENTRE_X = 161
Y_TWO_LINES = 114
Y_ONE_LINE = 123


def render(lines):
    font = ImageFont.truetype(str(FONT), int(round(SIZE * SCALE)))
    asc = font.getmetrics()[0]
    boxes = [font.getbbox(t, stroke_width=STROKE) for t in lines]
    widths = [b[2] - b[0] for b in boxes]
    w = (max(widths) + SCALE - 1) // SCALE + 4
    w = (w + 15) & ~15
    h = LINE_H * (len(lines) - 1) + 13 + (3 if any(c in "gjpqy," for c in lines[-1]) else 0)
    img = Image.new("L", (w * SCALE, h * SCALE), 0)
    draw = ImageDraw.Draw(img)
    for i, (t, b) in enumerate(zip(lines, boxes)):
        x = (w * SCALE - widths[i]) // 2 - b[0]
        draw.text((x, (BASELINE + 1 + i * LINE_H) * SCALE - asc), t, fill=255, font=font,
                  stroke_width=STROKE, stroke_fill=255)
    a = np.asarray(img, dtype=np.float32).reshape(h, SCALE, w, SCALE).mean(axis=(1, 3)) / 255.0
    return np.clip(np.round(a * 15), 0, 15).astype(np.uint8), w, h


def pack_i4(levels):
    """Stored as the staged sprites are (nds_source2d.c ndsS2DReadRaw): each
    odd row's 32-bit words swapped in pairs (TMEM's interleave, eight texels
    at 4 bits), then each word's bytes reversed (the loader's swap)."""
    levels = levels.copy()
    h, w = levels.shape
    odd = levels[1::2].reshape(-1, w // 16, 2, 8)
    levels[1::2] = odd[:, :, ::-1, :].reshape(-1, w)
    hi = levels[:, 0::2]
    lo = levels[:, 1::2]
    packed = ((hi << 4) | lo).astype(np.uint8)
    return packed.reshape(-1, 4)[:, ::-1].tobytes()


def main():
    unlocks = json.loads((ROOT / "scripts" / "p7" / "unlocks.json").read_text(encoding="utf-8"))
    text = json.loads((ROOT / "scripts" / "p7" / "messages.json").read_text(encoding="utf-8"))
    rows = []
    for r in unlocks["fighters"]:
        name = r["name"]
        rows.append([f"You can now use {name},", f"{text['fighters'][name]}."])
    for r in unlocks["stages"]:
        rows.append(["A new battle arena has been added:", f"{text['stages'][r['stage']]}!"])
    blob = bytearray()
    table = []
    for index, lines in enumerate(rows):
        levels, w, h = render(lines)
        offset = len(blob)
        blob += pack_i4(levels)
        x = CENTRE_X - w // 2
        y = Y_TWO_LINES if len(lines) == 2 else Y_ONE_LINE
        table.append((index, w, h, x, y, offset, " / ".join(lines)))
    out = ["/* Generated by scripts/p7/generate_p7_messages.py from scripts/p7/messages.json",
           " * and scripts/p7/unlocks.json. Do not edit. The texels are NitroFS",
           " * p7/messages.bin (assets/p7/messages.bin), offsets past its 8 B header. */",
           f"#define NDS_P7_MESSAGE_COUNT {len(table)}u",
           f"#define NDS_P7_MESSAGE_BYTES {len(blob)}u",
           f"#define NDS_P7_MESSAGE_MAGIC 0x{MAGIC:08X}u",
           "static const NDSP7Message sNdsP7Messages[NDS_P7_MESSAGE_COUNT] = {"]
    for index, w, h, x, y, offset, label in table:
        safe = label.replace("*/", "* /")
        out.append(f"    {{ {index}u, {w}u, {h}u, {x}, {y}, {offset}u }}, /* {safe} */")
    out.append("};")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    BLOB.parent.mkdir(parents=True, exist_ok=True)
    BLOB.write_bytes(MAGIC.to_bytes(4, "little") + len(blob).to_bytes(4, "little") + bytes(blob))
    print(f"{len(table)} messages, {len(blob)} bytes -> {OUT.relative_to(ROOT)}, {BLOB.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
